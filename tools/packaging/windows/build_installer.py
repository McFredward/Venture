#!/usr/bin/env python3
"""Turn a Windows release layout into Venture-windows64.zip and -setup.exe.

The layout is the directory tools/package_release.py writes on Windows
(dist/Venture-win64): its release-files.json manifest is verified first and
is the only source of the file list. The zip extracts to a Venture folder;
the installer is built with NSIS (makensis runs on Windows and Linux).
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
import tempfile
import time
import zipfile

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
NSI = HERE / "venture.nsi"
MANIFEST = "release-files.json"
REQUIRED = ("venture.exe", "venture-runtime.exe")


def project_version():
    text = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = re.search(r"project\(\s*Venture\s+VERSION\s+(\d+(?:\.\d+){0,3})", text)
    if not match:
        raise RuntimeError("Cannot read the project version from CMakeLists.txt")
    return match.group(1)


def load_layout(layout):
    """Return the manifest's files after checking the layout matches it exactly."""
    manifest = layout / MANIFEST
    if not manifest.is_file():
        raise RuntimeError("Not a release layout (no " + MANIFEST + "): " + str(layout))
    files = json.loads(manifest.read_text(encoding="utf-8"))["files"]
    actual = set()
    for path in layout.rglob("*"):
        if path.is_symlink():
            raise RuntimeError("Release layout must not contain links: " + path.relative_to(layout).as_posix())
        if path.is_file():
            actual.add(path.relative_to(layout).as_posix())
    if actual != set(files) | {MANIFEST}:
        extra, missing = sorted(actual - set(files) - {MANIFEST}), sorted(set(files) - actual)
        raise RuntimeError("Layout differs from its manifest; extra: %s missing: %s" % (extra[:5], missing[:5]))
    for name, entry in files.items():
        relative = PurePosixPath(name)
        if relative.is_absolute() or ".." in relative.parts or ":" in name or "\\" in name:
            raise RuntimeError("Unsafe manifest path: " + name)
        data = (layout / name).read_bytes()
        if len(data) != entry["bytes"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise RuntimeError("Layout file changed after packaging: " + name)
    for name in REQUIRED:
        if name not in files:
            raise RuntimeError("Release layout lacks " + name)
    return sorted(files) + [MANIFEST]


def write_zip(layout, names, target, folder="Venture"):
    """Deterministic zip (sorted entries, fixed metadata) extracting to folder/."""
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    temporary = target.with_name(target.name + ".partial")
    with zipfile.ZipFile(temporary, "w", zipfile.ZIP_DEFLATED, allowZip64=True) as archive:
        for name in names:
            path = layout / name
            stamp = int(epoch) if epoch else int(path.stat().st_mtime)
            info = zipfile.ZipInfo(folder + "/" + name, time.gmtime(max(stamp, 315532800))[:6])
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 0
            info.external_attr = 0x20  # FILE_ATTRIBUTE_ARCHIVE
            with path.open("rb") as source, archive.open(info, "w", force_zip64=path.stat().st_size >= 1 << 31) as sink:
                shutil.copyfileobj(source, sink, 1 << 20)
    temporary.replace(target)


def nsis_string(value):
    if any(c in value for c in '"\r\n'):
        raise RuntimeError("Unsupported character in path: " + value)
    return value.replace("$", "$$")


def nsis_lists(layout, names, directory):
    """Write the installer's File commands and the uninstaller's removal list."""
    install = ["; Generated by build_installer.py from " + MANIFEST]
    current = None
    for name in names:
        relative = PurePosixPath(name)
        parent = "\\".join(relative.parent.parts)
        if parent != current:
            install.append('SetOutPath "$INSTDIR%s"' % nsis_string("\\" + parent if parent else ""))
            current = parent
        source = str((layout / name).resolve())
        if "${" in source or '"' in source:
            raise RuntimeError("Unsupported character in path: " + source)
        # Run-time strings escape $; compile-time source paths are literal.
        install.append('File "/oname=%s" "%s"' % (nsis_string(relative.name), source))
    directories = {PurePosixPath(name).parent for name in names} - {PurePosixPath(".")}
    for path in list(directories):
        directories.update(p for p in path.parents if p != PurePosixPath("."))
    removal = [name.replace("/", "\\") for name in names]
    removal += ["\\".join(d.parts) + "\\" for d in sorted(directories, key=lambda d: (-len(d.parts), d.as_posix()))]
    install_path = directory / "install-files.nsh"
    list_path = directory / "uninstall.lst"
    install_path.write_text("\n".join(install) + "\n", encoding="utf-8-sig")
    list_path.write_bytes(("\r\n".join(removal) + "\r\n").encode("ascii"))
    return install_path, list_path


def find_makensis(explicit=None):
    candidates = [explicit] if explicit else [
        str(ROOT / ".deps/nsis/makensis.exe"), shutil.which("makensis"), shutil.which("makensis.exe")]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return Path(candidate)
    raise RuntimeError("makensis not found; pass --makensis (NSIS 3.x)")


def build_installer(layout, names, target, version, makensis, icon=None):
    quad = ".".join((version.split(".") + ["0"] * 4)[:4])
    size_kb = (sum((layout / n).stat().st_size for n in names) + 1023) // 1024
    environment = dict(os.environ)
    # A makensis unpacked from a distribution package keeps its data beside it.
    share = makensis.resolve().parent.parent / "share/nsis"
    if "NSISDIR" not in environment and (share / "Stubs").is_dir():
        environment["NSISDIR"] = str(share)
    with tempfile.TemporaryDirectory(prefix="venture-nsis-") as temporary:
        install, removal = nsis_lists(layout, names, Path(temporary))
        partial = target.with_name(target.name + ".partial")
        defines = {"VERSION": version, "VERSION_QUAD": quad, "OUTFILE": str(partial),
                   "INSTALL_FILES": str(install), "UNINSTALL_LIST": str(removal), "SIZE_KB": str(size_kb)}
        if icon:
            defines["ICON"] = str(Path(icon).resolve())
        command = [str(makensis), "-V2", "-INPUTCHARSET", "UTF8", "-WX"]
        command += ["-D%s=%s" % item for item in defines.items()] + [str(NSI)]
        subprocess.run(command, check=True, env=environment)
        partial.replace(target)


def release_layout_tools():
    spec = importlib.util.spec_from_file_location("package_release", ROOT / "tools/package_release.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--layout", type=Path, default=ROOT / "dist/Venture-win64", help="Windows release layout")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "dist")
    parser.add_argument("--name", default="Venture-windows64", help="output base name (keep 'windows' in it)")
    parser.add_argument("--version", default=None, help="defaults to the CMake project version")
    parser.add_argument("--makensis", help="makensis executable (default: .deps/nsis or PATH)")
    parser.add_argument("--icon", help="optional .ico for the installer and uninstaller")
    parser.add_argument("--readobj", help="llvm-readobj: audit the layout's PE imports first")
    parser.add_argument("--no-zip", action="store_true")
    parser.add_argument("--no-installer", action="store_true")
    args = parser.parse_args(argv)
    if "windows" not in args.name.lower():
        parser.error("--name must contain 'windows' (the website matches it)")
    layout = args.layout.resolve()
    names = load_layout(layout)
    if args.readobj:
        release_layout_tools().check_imports(layout, args.readobj)
    version = args.version or project_version()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs = []
    if not args.no_zip:
        outputs.append(args.output_dir / (args.name + ".zip"))
        write_zip(layout, names, outputs[-1])
    if not args.no_installer:
        outputs.append(args.output_dir / (args.name + "-setup.exe"))
        build_installer(layout, names, outputs[-1], version, find_makensis(args.makensis), args.icon)
    for path in outputs:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        print("%s  %s  (%.1f MiB)" % (digest, path.name, path.stat().st_size / 1048576))


if __name__ == "__main__":
    main()
