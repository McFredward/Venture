#!/usr/bin/env python3
"""Generate Android 12L JNI slot table (229 functions + four reserved words).

Input: android-12.1.0_r1 libnativehelper/include_jni/jni.h (Apache-2.0).
https://android.googlesource.com/platform/libnativehelper/+/refs/tags/android-12.1.0_r1/include_jni/jni.h
"""
import hashlib
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
source = Path(__file__).with_name("android_jni.h").read_bytes()
# The upstream file has one extra blank line at EOF. The vendored copy removes
# only that line; original upstream SHA-256:
# 5df9074457c041b372f2c68ff646d6e8600cd673a223885e8df21c44c94ec667
if hashlib.sha256(source).hexdigest() != "1b88ab7befd43180b622395c8c5c85759de8689f05d05d27e8a5cf543ac4a60b":
    raise SystemExit("Android JNI contract header hash mismatch")
table = source.decode().split("struct JNINativeInterface {")[1].split("\n};")[0]
names = re.findall(r"\(\*(\w+)\)", table)
assert len(names) == 229 and names[-1] == "GetObjectRefType"
special = {"GetVersion", "DefineClass", "FindClass", "GetMethodID", "GetStaticMethodID", "GetFieldID", "GetObjectField", "FromReflectedMethod", "RegisterNatives", "UnregisterNatives", "GetJavaVM", "GetStringUTFChars", "ReleaseStringUTFChars"}
rows = ["// Generated by tools/dex/generate_jni.py. Android 12L, JNI 1.6; slots 0..3 reserved."]
for slot, name in enumerate(names, 4):
    match = re.fullmatch(r"Call(Static|Nonvirtual)?(Object|Boolean|Byte|Char|Short|Int|Long|Float|Double|Void)Method(V|A)?", name)
    if match:
        kind, typ, form = match.groups()
        rows.append(f"JNI_CALL({slot}, {name}, {kind or 'Virtual'}, {typ}, {dict(V='VaList', A='Array').get(form, 'Ellipsis')})")
    elif name.startswith("NewObject") and name in ("NewObject", "NewObjectV", "NewObjectA"):
        rows.append(f"JNI_CALL({slot}, {name}, Constructor, Object, {dict(V='VaList', A='Array').get(name[9:], 'Ellipsis')})")
    else:
        rows.append(f"JNI_{'SPECIAL' if name in special else 'FIXED'}({slot}, {name})")
(ROOT / "src/runtime/java/jni_slots.inc").write_text("\n".join(rows) + "\n", encoding="utf-8")
