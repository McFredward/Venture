#!/usr/bin/env python3
"""Capture compiler-created AAPCS32 entry images; requires unicorn + pyelftools.

Unicorn only executes NDK-compiled callers; no hand-authored argument-placement
oracle or Venture marshaler is involved. Sinks contain just bx lr and are
intercepted before execution. Outputs can be regenerated and byte-compared.
"""
import argparse
import hashlib
import io
import json
import struct
import subprocess
import tempfile
from pathlib import Path
from elftools.elf.elffile import ELFFile
from unicorn import Uc, UC_ARCH_ARM, UC_MODE_ARM, UC_HOOK_CODE
from unicorn.arm_const import UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3, UC_ARM_REG_SP, UC_ARM_REG_LR, UC_ARM_REG_CPSR, UC_ARM_REG_FPEXC

ROOT = Path(__file__).resolve().parents[2]

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--ndk', type=Path, default=ROOT / '.deps/android-ndk')
    p.add_argument('--output', type=Path, default=ROOT / 'tests/runtime/a32_compiler_images.inc')
    a = p.parse_args()
    bin_dir = next((a.ndk / 'toolchains/llvm/prebuilt').iterdir()) / 'bin'
    clang = bin_dir / ('clang.exe' if (bin_dir / 'clang.exe').exists() else 'clang')
    source = ROOT / 'tests/guest/a32_abi_callers.c'
    cases = ['mixed', 'skip', 'split', 'narrow', 'varargs', 'sret']
    captures = []
    with tempfile.TemporaryDirectory(prefix='venture-a32-oracle-') as tmp:
        tmp = Path(tmp)
        sinks = tmp / 'sinks.s'
        sinks.write_text('.syntax unified\n.arm\n.text\n' + ''.join(f'.global sink_{n}\n.type sink_{n},%function\nsink_{n}:\n bx lr\n' for n in cases + ['result']))
        for thumb in (False, True):
            elf = tmp / 'callers.elf'
            command = [str(clang), '--target=armv7a-linux-androideabi23', '-O2', '-mthumb' if thumb else '-marm', '-mfloat-abi=softfp', '-mfpu=neon', '-fno-pic', '-fno-pie', '-nostdlib', '-static', '-Wl,--image-base=0x10000', '-Wl,-e,call_mixed', str(source), str(sinks), '-o', str(elf)]
            run = subprocess.run(command, check=True, capture_output=True)
            if elf.read_bytes()[:4] != b'\x7fELF':
                raise RuntimeError((elf.read_bytes()[:100], run.stderr.decode(errors='replace'), command))
            image = ELFFile(io.BytesIO(elf.read_bytes()))
            symbols = {s.name: s['st_value'] for s in image.get_section_by_name('.symtab').iter_symbols()}
            for name in cases:
                cpu = Uc(UC_ARCH_ARM, UC_MODE_ARM)
                cpu.mem_map(0x10000, 0x10000)
                cpu.mem_map(0x200000, 0x10000)
                for segment in image.iter_segments():
                    if segment['p_type'] == 'PT_LOAD' and segment['p_vaddr'] >= 0x10000:
                        cpu.mem_write(segment['p_vaddr'], segment.data())
                cpu.reg_write(UC_ARM_REG_SP, 0x20f000)
                cpu.reg_write(UC_ARM_REG_LR, 0x1fff0)
                cpu.reg_write(UC_ARM_REG_FPEXC, 0x40000000)
                # Seed unallocated/skipped slots so accidental backfilling is visible.
                for register in (UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3): cpu.reg_write(register, 0xa5a5a5a5)
                captured = []
                def hook(uc, address, size, user):
                    if address == (symbols['sink_' + name] & ~1):
                        regs = [uc.reg_read(r) for r in (UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3)]
                        sp = uc.reg_read(UC_ARM_REG_SP)
                        stack = list(struct.unpack('<16I', uc.mem_read(sp, 64)))
                        captured.append(dict(name=name, thumb=thumb, registers=regs, stack=stack, sp=sp))
                        uc.emu_stop()
                cpu.hook_add(UC_HOOK_CODE, hook)
                cpu.emu_start(symbols['call_' + name], 0x1fff0, count=1000)
                assert len(captured) == 1, name
                captures += captured
    lines = ['// Generated by a32_call_oracle.py using NDK r30 clang + Unicorn 2.1.4.',
             '// Source SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
             'static constexpr CompilerImage compiler_images[] = {']
    for c in captures:
        words = lambda ws: '{' + ', '.join(f'0x{w:08x}u' for w in ws) + '}'
        lines.append('  {"' + c['name'] + '", ' + str(c['thumb']).lower() + ', ' + words(c['registers']) + ', ' + words(c['stack']) + '},')
    a.output.write_text('\n'.join(lines + ['};', '']))
    print(f'Captured {len(captures)} compiler-produced ARM/Thumb entry images')

if __name__ == '__main__': main()

