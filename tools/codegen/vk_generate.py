#!/usr/bin/env python3
"""Generate ARM64 Vulkan entry points and chain metadata from pinned vk.xml.

Platform ABIs other than Android are deliberately excluded, as are provisional
extensions. All aliases retain their exact entry point names and dispatch scope.
Semantic translation lives in hle/vulkan, not in the XML registry.
"""
import argparse
import pathlib
import re
import xml.etree.ElementTree as ET


def generate(registry, output):
    root = ET.parse(registry).getroot()
    commands = {c.get('name') or c.findtext('proto/name'): c
                for c in root.findall('commands/command') if c.get('api', 'vulkan') != 'vulkansc'}
    types = {t.get('name') or t.findtext('name'): t for t in root.findall('types/type')}
    owners, versions, enabled_types = {}, {}, set()
    for feature in root.findall('feature'):
        if 'vulkan' not in feature.get('api', '').split(',') or float(feature.get('number', '9')) > 1.4:
            continue
        major, minor = feature.get('number').split('.')
        for req in feature.findall('require'):
            if req.get('api', 'vulkan') != 'vulkan':
                continue
            enabled_types.update(x.get('name') for x in req.findall('type'))
            for c in req.findall('command'):
                versions[c.get('name')] = f'VK_MAKE_API_VERSION(0, {major}, {minor}, 0)'
                owners.setdefault(c.get('name'), [])
    allowed_exts = set()
    for ext in root.findall('extensions/extension'):
        if ('vulkan' not in ext.get('supported', '').split(',') or ext.get('provisional') == 'true'
                or ext.get('platform') not in (None, 'android')):
            continue
        allowed_exts.add(ext.get('name'))
        for req in ext.findall('require'):
            if req.get('api', 'vulkan') != 'vulkan':
                continue
            enabled_types.update(x.get('name') for x in req.findall('type'))
            for c in req.findall('command'):
                owners.setdefault(c.get('name'), []).append(ext.get('name'))

    # A protected extension may also name unprotected helper structures. Only
    # emit types in the unprotected/Android dependency closure.
    pending = list(enabled_types)
    while pending:
        t = types.get(pending.pop())
        if t is None:
            continue
        deps = [m.findtext('type') for m in t.findall('member')]
        deps += [t.get('alias'), t.get('requires')]
        for d in deps:
            if d and d not in enabled_types:
                enabled_types.add(d)
                pending.append(d)

    def canonical(name):
        c = commands[name]
        return canonical(c.get('alias')) if c.get('alias') else name

    def surface_type(name, visiting=frozenset()):
        if name == 'VkSurfaceKHR':
            return True
        if name in visiting:
            return False
        t = types.get(name)
        if t is None:
            return False
        if t.get('alias'):
            return surface_type(t.get('alias'), visiting | {name})
        return any(surface_type(m.findtext('type'), visiting | {name})
                   for m in t.findall('member') if 'vulkan' in m.get('api', 'vulkan').split(','))

    lines = ['// Generated by vk_generate.py; do not edit.']
    entries = []
    for slot, name in enumerate(sorted(owners)):
        cname = canonical(name)
        c = commands[cname]
        params = [p for p in c.findall('param') if 'vulkan' in p.get('api', 'vulkan').split(',')]
        first = params[0].findtext('type') if params else ''
        scope = {'VkInstance': 'instance', 'VkPhysicalDevice': 'physical', 'VkDevice': 'device',
                 'VkQueue': 'queue', 'VkCommandBuffer': 'command_buffer'}.get(first, 'global')
        if name == 'vkGetInstanceProcAddr':
            scope = 'global'
        # Registry scope and signature define candidate families. Layer and
        # allocator safety are decided at runtime, never from a title name.
        eligible = (scope != 'queue' and
                    (cname.startswith('vkCmd') or cname.startswith('vkGet') or
                     cname in {'vkUpdateDescriptorSets', 'vkUpdateDescriptorSetWithTemplate',
                               'vkAllocateDescriptorSets', 'vkFreeDescriptorSets', 'vkResetDescriptorPool',
                               'vkFlushMappedMemoryRanges', 'vkInvalidateMappedMemoryRanges',
                               'vkResetCommandBuffer', 'vkBeginCommandBuffer', 'vkEndCommandBuffer'}))
        eligible &= not any(p.findtext('type') == 'VkAllocationCallbacks' or
                            p.findtext('type', '').startswith('PFN_') for p in params)
        eligible &= 'Debug' not in cname and not any(p.findtext('name') == 'timeout' for p in params)
        # Instance-owned surfaces can retain guest allocators independently of
        # the device. Device-only snapshots cannot establish their safety.
        eligible &= not any(surface_type(p.findtext('type')) for p in params)
        # Even integer-only signatures can reach FP code in the native driver.
        # Preserve host rounding/FTZ and keep driver flags out of guest FPSR.
        execution = 'InJitFp' if eligible else 'RunLoop'
        handle = '0' if scope == 'global' else 'reinterpret_cast<GuestAddr>(a0)'
        lines.append(f'static void dispatch_{name}(hle::CallContext& ctx) {{')
        lines.append('  Invocation args(ctx);')
        for i, p in enumerate(params):
            lines.append(f'  auto a{i} = args.read<Argument<{i}, PFN_{name}>>();')
        if scope == 'device':
            for i, p in enumerate(params):
                if p.findtext('type') == 'VkAllocationCallbacks':
                    lines.append(f'  retain_device_allocator(a0, a{i});')
        if scope in {'physical', 'device', 'command_buffer'}:
            lines.append('  args.host_context(a0);')
        for i, p in enumerate(params):
            if p.findtext('type') in {'VkPipelineStageFlags', 'VkPipelineStageFlags2', 'VkPipelineStageFlags2KHR'}:
                lines.append(f'  args.density_stages(a{i});')
            if p.findtext('type') == 'VkImageLayout':
                lines.append(f'  args.density_layout(a{i});')
            if p.findtext('type') == 'VkFormat' and '*' not in ''.join(p.itertext()):
                lines.append(f'  args.depth_format(a{i});')
            count = p.get('len', '1').split(',')[0]
            if count == 'null-terminated':
                count = '1'
            for j, other in enumerate(params):
                count = re.sub(r'\b'+other.findtext('name')+r'\b', f'a{j}', count)
            count = count.replace('::', '->')
            if not re.fullmatch(r'[\w\s*+/>.()\-]+', count) or 'latexmath' in count:
                count = '1'
            lines.append(f'  args.prepare(a{i}, {count});')
        lines.append(f'  args.invoke<PFN_{name}, "{name}", {slot}>(Scope::{scope}, {handle}'
                     + ''.join(f', a{i}' for i in range(len(params))) + ');')
        lines.append('}')
        if eligible:
            lines += [f'static bool try_{name}(hle::CallContext& ctx) {{', '  Invocation args(ctx, true);',
                      f'  if (!args.admit<"{name}", {slot}>(Scope::{scope}, {"0" if scope == "global" else "ctx.x(0)"})) return false;']
            for i, p in enumerate(params):
                lines.append(f'  auto a{i} = args.read<Argument<{i}, PFN_{name}>>();')
            if scope in {'physical', 'device', 'command_buffer'}:
                lines.append('  args.host_context(a0);')
            for i, p in enumerate(params):
                if p.findtext('type') in {'VkPipelineStageFlags', 'VkPipelineStageFlags2', 'VkPipelineStageFlags2KHR'}:
                    lines.append(f'  args.density_stages(a{i});')
                if p.findtext('type') == 'VkImageLayout':
                    lines.append(f'  args.density_layout(a{i});')
                if p.findtext('type') == 'VkFormat' and '*' not in ''.join(p.itertext()):
                    lines.append(f'  args.depth_format(a{i});')
                if p.findtext('type') == 'VkQueryResultFlags':
                    lines.append(f'  if (a{i} & VK_QUERY_RESULT_WAIT_BIT) return false;')
                count = p.get('len', '1').split(',')[0]
                if count == 'null-terminated':
                    count = '1'
                for j, other in enumerate(params):
                    count = re.sub(r'\b'+other.findtext('name')+r'\b', f'a{j}', count)
                count = count.replace('::', '->')
                if not re.fullmatch(r'[\w\s*+/>.()\-]+', count) or 'latexmath' in count:
                    count = '1'
                lines.append(f'  args.prepare(a{i}, {count});')
            lines.append(f'  return args.invoke<PFN_{name}, "{name}", {slot}>(Scope::{scope}, {handle}'
                         + ''.join(f', a{i}' for i in range(len(params))) + ');')
            lines.append('}')
        observer = 'nullptr'
        if c.findtext('proto/type') == 'VkResult':
            observer = f'reinterpret_cast<PFN_vkVoidFunction>(driver_{name})'
            declarations = ', '.join(f'Argument<{i}, PFN_{name}> a{i}' for i in range(len(params)))
            lines.append(f'static VkResult VKAPI_CALL driver_{name}({declarations}) {{')
            lines.append(f'  return driver_result<PFN_{name}, {slot}>("{name}", Scope::{scope}, {handle}'
                         + ''.join(f', a{i}' for i in range(len(params))) + ');')
            lines.append('}')
        elif scope == 'queue' and c.findtext('proto/type') == 'void':
            observer = f'reinterpret_cast<PFN_vkVoidFunction>(driver_{name})'
            declarations = ', '.join(f'Argument<{i}, PFN_{name}> a{i}' for i in range(len(params)))
            lines.append(f'static void VKAPI_CALL driver_{name}({declarations}) {{')
            lines.append(f'  driver_queue_void<PFN_{name}, {slot}>("{name}", {handle}'
                         + ''.join(f', a{i}' for i in range(len(params))) + ');')
            lines.append('}')
        entries.append(f'  {{"{name}", "{cname}", Scope::{scope}, {versions.get(name, "0")}, '
                       f'"{",".join(owners[name])}", dispatch_{name}, {observer}, hle::Execution::{execution}, '
                       f'{"try_" + name if eligible else "nullptr"}}},')
    lines += ['static const Command commands[] = {', *entries, '};']
    lines += ['static constexpr std::string_view registry_extensions[] = {']
    lines += [f'  "{e}",' for e in sorted(allowed_exts)]
    lines += ['};']

    structs = ['// Generated by vk_generate.py; do not edit.', 'switch (type) {']
    members = ['// Generated by vk_generate.py; do not edit.', 'switch (base->sType) {']
    borrow_traits = ['// Generated by vk_generate.py; do not edit.', 'switch (type) {']
    borrow_members = ['// Generated by vk_generate.py; do not edit.', 'switch (base->sType) {']
    def resolved_type(name):
        t = types.get(name)
        return resolved_type(t.get('alias')) if t is not None and t.get('alias') else t

    struct_types = {n for n in types if (t := resolved_type(n)) is not None
                    and t.get('category') == 'struct'
                    and any(m.findtext('name') == 'sType' for m in t.findall('member'))}

    # Generate the identity-density boundary from registry member types and
    # extension ownership, including legacy non-sType attachment descriptions.
    density_members = {
        'VkImageLayout': ('density_layout', '== VK_IMAGE_LAYOUT_FRAGMENT_DENSITY_MAP_OPTIMAL_EXT'),
        'VkImageUsageFlags': ('density_usage', '& VK_IMAGE_USAGE_FRAGMENT_DENSITY_MAP_BIT_EXT'),
        'VkImageUsageFlags2KHR': ('density_usage', '& VK_IMAGE_USAGE_2_FRAGMENT_DENSITY_MAP_BIT_EXT'),
        'VkImageCreateFlags': ('density_flags', '& VK_IMAGE_CREATE_SUBSAMPLED_BIT_EXT'),
        'VkImageViewCreateFlags': ('density_view_flags', '& (VK_IMAGE_VIEW_CREATE_FRAGMENT_DENSITY_MAP_DYNAMIC_BIT_EXT | VK_IMAGE_VIEW_CREATE_FRAGMENT_DENSITY_MAP_DEFERRED_BIT_EXT)'),
        'VkSamplerCreateFlags': ('density_sampler_flags', '& (VK_SAMPLER_CREATE_SUBSAMPLED_BIT_EXT | VK_SAMPLER_CREATE_SUBSAMPLED_COARSE_RECONSTRUCTION_BIT_EXT)'),
        'VkPipelineCreateFlags': ('density_pipeline_flags', '& VK_PIPELINE_CREATE_RENDERING_FRAGMENT_DENSITY_MAP_ATTACHMENT_BIT_EXT'),
        'VkPipelineCreateFlags2': ('density_pipeline_flags', '& VK_PIPELINE_CREATE_2_RENDERING_FRAGMENT_DENSITY_MAP_ATTACHMENT_BIT_EXT'),
        'VkPipelineStageFlags': ('density_stages', '& VK_PIPELINE_STAGE_FRAGMENT_DENSITY_PROCESS_BIT_EXT'),
        'VkPipelineStageFlags2': ('density_stages', '& VK_PIPELINE_STAGE_2_FRAGMENT_DENSITY_PROCESS_BIT_EXT'),
        'VkAccessFlags': ('density_access', '& VK_ACCESS_FRAGMENT_DENSITY_MAP_READ_BIT_EXT'),
        'VkAccessFlags2': ('density_access', '& VK_ACCESS_2_FRAGMENT_DENSITY_MAP_READ_BIT_EXT'),
    }
    def canonical_type(name):
        t = types.get(name)
        return canonical_type(t.get('alias')) if t is not None and t.get('alias') else name
    def density_member(m):
        text = ''.join(m.itertext())
        return density_members.get(canonical_type(m.findtext('type'))) if '*' not in text and '[' not in text else None
    plain_types = {n for n in enabled_types if (t := resolved_type(n)) is not None
                   and t.get('category') == 'struct' and n not in struct_types
                   and any(density_member(m) for m in t.findall('member'))}
    while True:
        more = {n for n in enabled_types if (t := resolved_type(n)) is not None
                and t.get('category') == 'struct' and n not in struct_types
                and any(m.findtext('type') in plain_types for m in t.findall('member'))}
        if more <= plain_types: break
        plain_types |= more
    # VkFormat values are copied so a 24-bit depth format the host cannot
    # attach reaches it as the 32-bit format Chain::depth_format substitutes.
    copy_types = struct_types | plain_types | {'VkFormat'}
    plain_members = ['// Generated by vk_generate.py; do not edit.',
                     'if constexpr (std::is_same_v<T, VkFormat>) {', '  depth_format(v);', '}']
    plain_borrow = ['// Generated by vk_generate.py; do not edit.',
                    'if constexpr (std::is_same_v<T, VkFormat>) {', '  if (depth_alias_candidate(v)) return false;', '}']
    for name in sorted(plain_types):
        t = types.get(name)
        if t is None or t.get('alias'): continue
        fields, checks = [], []
        for m in t.findall('member'):
            mt, mn = m.findtext('type'), m.findtext('name')
            if 'vulkan' not in m.get('api', 'vulkan').split(','): continue
            if rule := density_member(m):
                fields.append(f'  {rule[0]}(v.{mn});')
                checks.append(f'  if (v.{mn} {rule[1]}) return false;')
            if mt not in copy_types: continue
            text = ''.join(m.itertext())
            if '*' not in text and '[' not in text:
                fields.append(f'  copy_value(v.{mn});')
                checks.append(f'  if (!borrow_value(v.{mn}, depth, budget)) return false;')
            elif text.startswith('const ') and text.count('*') == 1:
                count = m.get('len', '1').split(',')[0]
                if re.fullmatch(r'\w+', count):
                    count = count if count.isdigit() or count.isupper() else 'v.' + count
                    fields.append(f'  v.{mn} = copy_array(v.{mn}, {count});')
                    checks.append(f'  if (!borrow_array(v.{mn}, {count}, depth, budget)) return false;')
        plain_members += [f'if constexpr (std::is_same_v<T, {name}>) {{', *fields, '}']
        plain_borrow += [f'if constexpr (std::is_same_v<T, {name}>) {{', *checks, '}']
    plain_borrow += ['return true;']
    structure_owners = {}
    for ext in root.findall('extensions/extension'):
        if ext.get('name') not in allowed_exts: continue
        for req in ext.findall('require'):
            for node in req.findall('type'):
                structure_owners.setdefault(canonical_type(node.get('name')), set()).add(ext.get('name'))
    extension_map = ['// Generated by vk_generate.py; do not edit.', 'switch (type) {']
    owner_seen = set()
    for name in sorted(enabled_types):
        t = types.get(name)
        if t is None or t.get('category') != 'struct' or t.get('alias') or not t.get('structextends'): continue
        st = next((m.get('values') for m in t.findall('member') if m.findtext('name') == 'sType'), None)
        owners_for_type = structure_owners.get(name, set())
        if st and st not in owner_seen and owners_for_type:
            owner_seen.add(st)
            extension_map.append(f'  case {st}: return "' + '|'.join(sorted(owners_for_type)) + '|";')
    extension_map += ['  default: return {};', '}']

    # Layout identity is necessary but not sufficient: callbacks, platform
    # pointers and external handle types have Venture translation semantics.
    # A64/x64 Vulkan scalar, enum and handle ABIs are identical on both hosts.
    translated_types = {'VkExternalMemoryHandleTypeFlags', 'VkExternalMemoryHandleTypeFlagBits',
                        'VkExternalSemaphoreHandleTypeFlags', 'VkExternalSemaphoreHandleTypeFlagBits',
                        'VkExternalFenceHandleTypeFlags', 'VkExternalFenceHandleTypeFlagBits'}
    # The texture and AHB layers consume these nodes and relink their private
    # chain copies. Borrowing them would let that relinking modify guest memory.
    translated_structs = {'VkImageViewASTCDecodeModeEXT', 'VkSamplerYcbcrConversionInfo'}
    borrow_cache = {}

    def borrowable_type(name, visiting=frozenset()):
        if name in borrow_cache:
            return borrow_cache[name]
        if name in visiting or name in translated_types or name in translated_structs or name.endswith('ANDROID'):
            return False
        alias = types.get(name)
        if alias is not None and alias.get('alias'):
            return borrowable_type(alias.get('alias'), visiting | {name})
        if name in {'void', 'char', 'float', 'double', 'int', 'uint8_t', 'int8_t',
                    'uint16_t', 'int16_t', 'uint32_t', 'int32_t', 'uint64_t', 'int64_t', 'size_t'}:
            return True
        t = resolved_type(name)
        if t is None:
            return False
        category = t.get('category')
        if category == 'funcpointer' or t.get('requires') in {'ANativeWindow', 'AHardwareBuffer'}:
            return False
        if category not in {'struct', 'union'}:
            return category in {'basetype', 'enum', 'bitmask', 'handle'}
        okay = True
        for m in t.findall('member'):
            mt, mn = m.findtext('type'), m.findtext('name')
            if mn == 'pNext' or 'vulkan' not in m.get('api', 'vulkan').split(','):
                continue
            text = ''.join(m.itertext())
            child = resolved_type(mt)
            if not borrowable_type(mt, visiting | {name}):
                okay = False
                break
            # Only direct sType graphs have generated dynamic walkers. Reject
            # opaque unions or non-sType wrappers that could hide such a graph.
            if mt in struct_types and (text.count('*') > 1 or (category == 'union')):
                okay = False
                break
            if mt in struct_types and '*' in text and not re.fullmatch(r'\w+', m.get('len', '1')):
                okay = False
                break
            if name not in struct_types and child is not None and child.get('category') == 'struct' and mt in struct_types:
                okay = False
                break
        borrow_cache[name] = okay
        return okay
    seen = set()
    for name in sorted(enabled_types):
        t = types.get(name)
        if t is None or t.get('category') != 'struct' or t.get('alias'):
            continue
        st = next((m.get('values') for m in t.findall('member') if m.findtext('name') == 'sType'), None)
        if st and st not in seen:
            seen.add(st)
            structs.append(f'  case {st}: return sizeof({name});')
            borrow = borrowable_type(name)
            borrow_traits.append(f'  case {st}: return {str(borrow).lower()};')
            if borrow:
                checks = []
                for m in t.findall('member'):
                    mt, mn = m.findtext('type'), m.findtext('name')
                    if mn == 'pNext' or 'vulkan' not in m.get('api', 'vulkan').split(','):
                        continue
                    # Queue-family FOREIGN is the only value-dependent member
                    # translation in otherwise ordinary recording structures.
                    if mn in {'srcQueueFamilyIndex', 'dstQueueFamilyIndex'}:
                        checks.append(f'      if (v.{mn} == VK_QUEUE_FAMILY_FOREIGN_EXT) return false;')
                    if rule := density_member(m):
                        checks.append(f'      if (v.{mn} {rule[1]}) return false;')
                    if mt not in copy_types:
                        continue
                    text = ''.join(m.itertext())
                    if '*' in text:
                        count = m.get('len', '1')
                        count = count if count.isdigit() or count.isupper() else 'v.' + count
                        checks.append(f'      if (!borrow_array(v.{mn}, {count}, depth, budget)) return false;')
                    elif '[' not in text:
                        checks.append(f'      if (!borrow_value(v.{mn}, depth, budget)) return false;')
                    elif mt == 'VkFormat':
                        raise SystemExit(f'{name}.{mn}: fixed VkFormat arrays have no borrow walker')
                    else:
                        checks.append(f'      for (const auto& item : v.{mn}) if (!borrow_chain(&item, depth, budget)) return false;')
                if checks:
                    borrow_members += [f'  case {st}: {{', f'      const auto& v = *reinterpret_cast<const {name}*>(base);',
                                       *checks, '      return true;', '  }']
            fields = []
            for m in t.findall('member'):
                mt, mn = m.findtext('type'), m.findtext('name')
                if mn == 'pNext' or 'vulkan' not in m.get('api', 'vulkan').split(','):
                    continue
                if rule := density_member(m):
                    fields.append(f'      {rule[0]}(v.{mn});')
                text = ''.join(m.itertext())
                if mt not in copy_types:
                    # Deferred submissions must own ABI-identical leaf arrays too.
                    if '*' in text and text.startswith('const ') and text.count('*') == 1:
                        leaf = types.get(mt)
                        category = leaf.get('category') if leaf is not None else None
                        count = m.get('len', '').split(',')[0]
                        if count and re.fullmatch(r'\w+', count) and count != 'null-terminated' and (
                                mt in {'uint8_t', 'uint16_t', 'uint32_t', 'uint64_t', 'int8_t', 'int16_t',
                                       'int32_t', 'int64_t', 'size_t', 'float', 'double', 'void'} or
                                category in {'basetype', 'handle', 'enum', 'bitmask'}):
                            count = count if count.isdigit() or count.isupper() else 'v.' + count
                            source = f'static_cast<const unsigned char*>(v.{mn})' if mt == 'void' else f'v.{mn}'
                            fields.append(f'      if (retain_arrays_) v.{mn} = copy_array({source}, {count});')
                        elif m.get('len'):
                            fields.append(f'      if (retain_arrays_ && v.{mn}) result_ = VK_ERROR_EXTENSION_NOT_PRESENT;')
                    continue
                if '*' not in text:
                    if '[' not in text:
                        fields.append(f'      copy_value(v.{mn});')
                    continue
                if text.count('*') > 1 or not text.startswith('const '):
                    continue
                count = m.get('len', '1').split(',')[0]
                if re.fullmatch(r'\w+', count):
                    count = count if count.isdigit() or count.isupper() else 'v.' + count
                    fields.append(f'      v.{mn} = copy_array(v.{mn}, {count});')
                else:
                    fields.append(f'      if (v.{mn}) result_ = VK_ERROR_EXTENSION_NOT_PRESENT;')
            if fields:
                members += [f'  case {st}: {{', f'      auto& v = *reinterpret_cast<{name}*>(base);', *fields, '      break;', '  }']
    structs += ['  default: return 0;', '}']
    members += ['  default: break;', '}']
    borrow_traits += ['  default: return false;', '}']
    borrow_members += ['  default: return structure_borrowable(base->sType);', '}']
    output.mkdir(parents=True, exist_ok=True)
    (output/'vk_plain_members.inc').write_text('\n'.join(plain_members)+'\n')
    (output/'vk_plain_borrow.inc').write_text('\n'.join(plain_borrow)+'\n')
    (output/'vk_structure_extensions.inc').write_text('\n'.join(extension_map)+'\n')
    (output/'vk_commands.inc').write_text('\n'.join(lines)+'\n')
    (output/'vk_structs.inc').write_text('\n'.join(structs)+'\n')
    (output/'vk_members.inc').write_text('\n'.join(members)+'\n')
    (output/'vk_borrow_traits.inc').write_text('\n'.join(borrow_traits)+'\n')
    (output/'vk_borrow_members.inc').write_text('\n'.join(borrow_members)+'\n')
    print(f'Vulkan registry: {len(entries)} commands, {len(seen)} chain structures')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
