"""C++ emission helpers. All sizes/offsets/slots originate in clang dumps."""
import json
import re

PRIMITIVES = {'void': ('void', 0), 'bool': ('bool', 1), 'char': ('char', 1),
              'signed char': ('std::int8_t', 1), 'unsigned char': ('std::uint8_t', 1),
              'short': ('std::int16_t', 2), 'unsigned short': ('std::uint16_t', 2),
              'int': ('std::int32_t', 4), 'unsigned int': ('std::uint32_t', 4),
              'long long': ('std::int64_t', 8), 'unsigned long long': ('std::uint64_t', 8),
              'float': ('float', 4), 'double': ('double', 8),
              'size_t': ('std::uint64_t', 8), 'CSteamID': ('std::uint64_t', 8),
              'CGameID': ('std::uint64_t', 8), 'uint64_steamid': ('std::uint64_t', 8),
              'uint64_gameid': ('std::uint64_t', 8)}


class Model:
    def __init__(self, api, abi):
        self.api, self.abi = api, abi
        self.aliases = {t['typedef']: t['type'] for t in api['typedefs']}
        self.enums = {e['enumname'] for e in api['enums']}
        self.records = {s['struct']: s for s in api['callback_structs'] + api['structs']}

    def scalar(self, typename):
        typename = re.sub(r'^const\s+', '',typename.strip())
        if re.fullmatch(r'u?int(8|16|32|64)_t', typename):
            return 'std::' + typename, int(re.search(r'\d+', typename)[0]) // 8
        if typename in PRIMITIVES:
            return PRIMITIVES[typename]
        if typename in self.enums or typename.startswith('ISteamHTMLSurface::E') or typename in ('EHTMLMouseButton','EHTMLKeyModifiers'):
            return 'std::int32_t', 4
        if typename in self.aliases:
            return self.scalar(self.aliases[typename])
        if '*' in typename or '&' in typename:
            return 'std::uint64_t', 8
        raise ValueError('not scalar: ' + typename)

    def array(self, typename):
        match = re.fullmatch(r'(.*?)\s*\[([0-9]+)\]', typename)
        return (match[1].strip(), int(match[2])) if match else (typename.strip(), 1)

    def size(self, typename, target):
        base, count = self.array(typename)
        if base in self.abi[target]:
            return count * self.abi[target][base]['size']
        return count * self.scalar(base)[1]

    def offset(self, record, field, target):
        fields = [f for f in self.abi[target][record]['fields'] if f['text'].endswith(' ' + field)]
        depth = min((f['indent'] for f in fields), default=0)
        matches = [f['offset'] for f in fields if f['indent'] == depth]
        if len(set(matches)) != 1:
            raise ValueError(f'ambiguous field: {record}.{field}: {matches}')
        return matches[0]

    def moves(self, record):
        result = []
        for f in self.records[record]['fields']:
            name, typ = f['fieldname'], f['fieldtype']
            go, ho = self.offset(record,name,'android'), self.offset(record,name,'windows')
            base, count = self.array(typ)
            if base in self.records:
                for i in range(count):
                    gs, hs = self.size(base,'android'), self.size(base,'windows')
                    result.extend((go+i*gs+g, ho+i*hs+h, n) for g,h,n in self.moves(base))
            else:
                gs, hs = self.size(typ,'android'), self.size(typ,'windows')
                if gs != hs:
                    raise ValueError('primitive width mismatch: ' + typ)
                result.append((go,ho,gs))
        # SDK JSON sometimes omits reserved union storage. Same-layout unions
        # must be retained in full (e.g. SteamNetworkingIdentity generic bytes).
        if record in ('SteamIPAddress_t','SteamNetworkingIdentity','SteamNetworkingIPAddr','SteamNetworkingConfigValue_t','RemotePlayInput_t','SteamInputActionEvent_t'):
            a,b = self.abi['android'][record],self.abi['windows'][record]
            if a['size'] != b['size'] or [(f['offset'],f['text'].split(' (anonymous')[0]) for f in a['fields']] != [(f['offset'],f['text'].split(' (anonymous')[0]) for f in b['fields']]:
                # Anonymous source paths differ by target only in path spelling;
                # top-level offsets/sizes are what establish identical storage.
                if a['size'] != b['size'] or [f['offset'] for f in a['fields']] != [f['offset'] for f in b['fields']]:
                    raise ValueError('union needs discriminated conversion: ' + record)
            return [(0,0,a['size'])]
        return list(dict.fromkeys(result))


def emit_layouts(model, version, includes):
    lines = ['// Generated by tools/codegen/steam/generate.py. Do not edit.',
             '#include "hle/steam/abi.h"', '#include <cstddef>', '#include <array>',
             includes.replace('"', '"', 1), f'namespace venture::steam::v{version} {{']
    rows = []
    for name, record in model.records.items():
        if name not in model.abi['android'] or name not in model.abi['windows']:
            continue
        guest, host = model.abi['android'][name], model.abi['windows'][name]
        moves = model.moves(name)
        lines += ['#ifdef _WIN32', f'static_assert(sizeof(::{name}) == {host["size"]});', '#else',
                  f'static_assert(sizeof(::{name}) == {guest["size"]});', '#endif']
        for f in record['fields']:
            field = f['fieldname']
            if name in ('servernetadr_t','gameserveritem_t'):
                continue  # SDK private members; sizeof checked above, clang checks offsets.
            member = 'm_val.' + field if name == 'SteamNetworkingConfigValue_t' and field not in ('m_eValue','m_eDataType') else field
            lines += ['#ifdef _WIN32',f'static_assert(offsetof(::{name}, {member}) == {model.offset(name,field,"windows")});',
                      '#else',f'static_assert(offsetof(::{name}, {member}) == {model.offset(name,field,"android")});','#endif']
        # Typed callback wire fields check the guest pack rules on the host
        # compiler too. Nested records retain the compiler's size/alignment.
        if 'callback_id' in record:
            lines += [f'#pragma pack(push, {guest["align"]})', f'struct Guest_{name} {{']
            for f in record['fields']:
                base,count = model.array(f['fieldtype'])
                if base in model.abi['android'] and base not in ('CSteamID','CGameID'):
                    r = model.abi['android'][base]
                    typ = f'alignas({r["align"]}) std::byte'
                    lines.append(f'  {typ} {f["fieldname"]}[{r["size"] * count}];')
                elif base in ('CSteamID','CGameID'):
                    lines.append(f'  std::byte {f["fieldname"]}[{8 * count}];')
                else:
                    typ,_ = model.scalar(base)
                    lines.append(f'  {typ} {f["fieldname"]}' + (f'[{count}]' if '[' in f['fieldtype'] else '') + ';')
            lines += ['};','#pragma pack(pop)',f'static_assert(sizeof(Guest_{name}) == {guest["size"]});']
            for f in record['fields']:
                lines.append(f'static_assert(offsetof(Guest_{name}, {f["fieldname"]}) == {model.offset(name,f["fieldname"],"android")});')
        lines += [f'static constexpr std::array<CopyField, {len(moves)}> fields_{name} {{{{']
        for g,h,n in moves:
            lines += ['#ifdef _WIN32', f'  {{{g}, {h}, {n}}},','#else', f'  {{{g}, {g}, {n}}},','#endif']
        lines += ['}};']
        rows += [f'  {{"{name}", {record.get("callback_id", -1)}, {guest["size"]}, sizeof(::{name}), fields_{name}}},']
    lines += ['static const Layout layouts[] = {', *rows, '};']
    lines += ['static constexpr Method methods[] = {']
    for m in model.abi['methods']:
        if m['slot'] is not None:
            lines.append(f'  {{"{m["symbol"]}", {m["slot"]}}},')
    lines += ['};', 'static constexpr Interface interfaces[] = {', '  {"ISteamClient", "SteamClient023", "SteamClient"},']
    for face in model.api['interfaces']:
        if not face.get('version_string'):
            continue
        for acc in face.get('accessors',[]):
            if acc['kind'] != 'gameserver':
                lines.append(f'  {{"{face["classname"]}", "{face["version_string"]}", "{acc["name_flat"]}"}},')
    lines += ['};']
    return lines


def emit_methods(model, version):
    lines, exports, skipped = [], [], []
    tables = {m['symbol']: m for m in model.abi['methods']}
    # Host-callback trampolines, networking message ownership and C++ response
    # objects belong to phase 2. No host ever receives a guest code pointer.
    unsafe_records = {'SteamNetworkingMessage_t','SteamNetworkingConfigValue_t','SteamInputActionEvent_t'}
    special = {'SteamAPI_ISteamUtils_GetAPICallResult'}
    def argument_type(typ):
        if '*' in typ or '&' in typ:
            return 'GuestAddr'
        return model.scalar(typ)[0]
    for face in model.api['interfaces']:
        classname = face['classname']
        if classname == 'ISteamClient':
            for m in face['methods']:
                name=m['methodname_flat']
                if not m['methodname'].startswith('GetISteam') or 'GameServer' in m['methodname']:
                    continue
                utils=m['methodname']=='GetISteamUtils'
                declaration='GuestAddr self, ' + ('' if utils else 'std::int32_t user, ') + 'std::int32_t pipe, const char* version'
                lines += [f'static GuestAddr f_{name}({declaration}) {{', '  Call c(self,"ISteamClient");',
                          '  if (pipe != c.bridge.pipe()' + ('' if utils else ' || user != c.bridge.user()') + ') throw std::runtime_error("Steam interface requested for foreign pipe/user");',
                          '  const auto* type = version ? c.bridge.sdk().interface(version) : nullptr;']
                expected=m['returntype'].replace('*','').strip()
                lines += [f'  if (!type' + ('' if expected=='void' else f' || type->name != "{expected}"') + ') return 0;',
                          '  return c.bridge.interface(version);','}']
                exports.append(f'  {{"{name}", hle::wrap<&f_{name}>()}},')
            continue
        if not face.get('version_string') or classname.startswith('ISteamGameServer'):
            continue
        for method in face['methods']:
            symbol = method['methodname_flat']
            entry = tables[symbol]
            if symbol in special:
                continue
            try:
                if entry['slot'] is None:
                    raise ValueError('SDK inline helper')
                if method['methodname'] in ('StartVRDashboard','SetVRHeadsetStreamingEnabled','InstallDLC','UninstallDLC','MarkContentCorrupt'):
                    raise ValueError('host client management is outside game runtime scope')
                if classname == 'ISteamNetworkingUtils' and method['methodname'] in ('SetConfigValue','GetConfigValue'):
                    raise ValueError('network config may contain guest function pointers; needs trampoline')
                result = method['returntype']
                flat_result = method.get('returntype_flat',result)
                composite_result = result in ('InputDigitalActionData_t','InputAnalogActionData_t','InputMotionData_t')
                if (result in model.records and not composite_result) or ('*' in result and 'char' not in result):
                    raise ValueError('composite or owned-object return needs adapter')
                rtype = 'void' if composite_result else argument_type(flat_result)
                params = method.get('params',[])
                native_types = re.search(r'\((.*)\)',entry['host_signature'])[1].split(', ')
                if not params:
                    native_types=[]
                if len(params) != len(native_types):
                    raise ValueError('native signature arity mismatch')
                pre, args, post, declarations = [], [], [], []
                for i,(p,native) in enumerate(zip(params,native_types)):
                    typ, flat = p['paramtype'], p.get('paramtype_flat',p['paramtype'])
                    name = f'a{i}'
                    base = re.sub(r'\bconst\b|[&*]', '',typ).strip()
                    if (base.startswith('ISteam') and '::E' not in base) or '(' in model.aliases.get(base,'') or base in unsafe_records:
                        raise ValueError('guest callback/object needs trampoline')
                    if 'Fn' in base or 'Hook' in base or 'Callback' in base:
                        raise ValueError('guest callback needs trampoline')
                    if typ in model.records:
                        gs,hs = model.size(typ,'android'),model.size(typ,'windows')
                        if hs<=8:
                            raise ValueError('small by-value record needs native scalar lowering')
                        if gs>16:
                            declarations.append(f'GuestAddr {name}')
                            pre.append(f'  Record r{i}(c.bridge.sdk(), "{typ}", g2h({name}));')
                        else:
                            words=(gs+7)//8
                            declarations += [f'std::uint64_t {name}_{j}' for j in range(words)]
                            pre += [f'  std::uint64_t words{i}[] = {{' + ', '.join(f'{name}_{j}' for j in range(words)) + '};',
                                    f'  Record r{i}(c.bridge.sdk(), "{typ}", words{i});']
                        args.append(f'r{i}.data()')
                        continue
                    declarations.append(f'{argument_type(flat)} {name}')
                    if '*' in typ or '&' in typ:
                        if base in model.records:
                            if '**' in typ or base not in model.abi['android']:
                                raise ValueError('record pointer array or opaque record')
                            count = '1'
                            # Array counts missing from JSON are supplied from
                            # the SDK declaration, reviewed by method name.
                            count_name = {'GetAvailableBeaconLocations':'uMaxNumLocations',
                                          'GetInput':'unMaxEvents'}.get(method['methodname'])
                            if method['methodname']=='GetConnectionRealTimeStatus' and p['paramname']=='pLanes':
                                count_name='nLanes'
                            count_name = p.get('array_count',count_name)
                            if 'out_array_count' in p:
                                # Same-layout inventory arrays can pass through;
                                # a changed layout requires an explicit capacity adapter.
                                if model.abi['android'][base] != model.abi['windows'][base]:
                                    if model.moves(base) != [(0,0,model.size(base,'android'))]:
                                        if model.size(base,'android') != model.size(base,'windows') or any(g!=h for g,h,n in model.moves(base)):
                                            raise ValueError('in/out record array capacity adapter required')
                                args.append(f'g2h({name})')
                                continue
                            if count_name:
                                index = next((j for j,q in enumerate(params) if q['paramname']==count_name),None)
                                if index is None:
                                    raise ValueError('unknown record array bound')
                                count = f'static_cast<std::size_t>(a{index})'
                            pre.append(f'  Record r{i}(c.bridge.sdk(), "{base}", g2h({name}), {count}, {"false" if "out_struct" in p else "true"});')
                            args.append(f'r{i}.data()')
                            if 'const' not in typ:
                                post.append(f'  r{i}.write_back();')
                        else:
                            args.append(f'g2h({name})')
                    else:
                        # Flat IDs are uint64; MSVC passes the 8-byte CSteamID
                        # argument directly. CSteamID *returns* use sret below.
                        args.append(f'static_cast<{model.scalar(native)[0]}>({name})')
                context = 'hle::CallContext& ctx, ' if composite_result else ''
                body = [f'static {rtype} f_{symbol}({context}GuestAddr self' + (', '+', '.join(declarations) if declarations else '') + ') {',
                        f'  Call c(self, "{classname}");',*pre]
                suffix = ', '+', '.join(args) if args else ''
                if composite_result:
                    hs=model.size(result,'windows')
                    if hs in (1,2,4,8):
                        body += [f'  auto result = member<std::uint{hs*8}_t>(c.self, {entry["slot"]}{suffix});',
                                 f'  return_record(ctx,c.bridge.sdk(),"{result}",&result,sizeof(result));']
                    else:
                        body += [f'  alignas(16) std::array<std::byte,{hs}> result{{}};',
                                 f'  member<void*>(c.self,{entry["slot"]},result.data(){suffix});',
                                 f'  return_record(ctx,c.bridge.sdk(),"{result}",result.data(),result.size());']
                elif result in ('CSteamID','CGameID'):
                    body += ['  std::uint64_t result{};',
                             f'  member<void*>(c.self, {entry["slot"]}, &result{suffix});']
                elif result == 'void':
                    body += [f'  member<void>(c.self, {entry["slot"]}{suffix});']
                else:
                    hr = 'void*' if '*' in result else model.scalar(result)[0]
                    body += [f'  auto result = member<{hr}>(c.self, {entry["slot"]}{suffix});']
                body += post
                if result != 'void' and not composite_result:
                    body += ['  return h2g(result);' if '*' in result else '  return result;']
                body += ['}']
                lines += body
                exports.append(f'  {{"{symbol}", hle::wrap<&f_{symbol}>()}},')
            except ValueError as error:
                skipped.append(dict(symbol=symbol,reason=str(error)))
        for acc in face.get('accessors',[]):
            if acc['kind']=='gameserver':
                continue
            name = acc['name_flat']
            lines += [f'static GuestAddr f_{name}() {{ return Bridge::get().interface("{face["version_string"]}"); }}']
            exports.append(f'  {{"{name}", hle::wrap<&f_{name}>()}},')
    lines += ['static const Export exports[] = {',*exports,'};']
    return lines, skipped
