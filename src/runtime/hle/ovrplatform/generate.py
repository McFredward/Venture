"""Regenerate ABI tables from pinned SDK declarations; never inspect credentials.

Run after tools/bootstrap.py --platform-sdk. --evidence points at r5/evidence
to refresh the per-game coverage fixture. Generated files are checked in; normal
builds need neither downloaded SDKs nor game binaries.
"""
import argparse
import csv
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def generate(evidence=None):
    enums = {}
    signatures = {}
    native = set()
    enum_types = set()
    string_getters = set()
    pins = json.loads((HERE / "sdk_sources.json").read_text())
    for source in pins["inputs"]:
        path = ROOT / ".deps" / source["path"]
        blob = path.read_bytes()
        assert hashlib.sha256(blob).hexdigest() == source["sha256"], path
        text = blob.decode("utf-8-sig")
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
        for name, value in re.findall(r"(?:ovrMessage_)?(\w+)\s*=\s*(0x[0-9A-Fa-f]+)", text):
            value = int(value, 16)
            if name in enums:
                assert enums[name] == value, (path, name)
            enums[name] = value
        if path.suffix == ".h":
            enum_types.update(re.findall(r'typedef\s+enum\s+\w*\s*\{[^}]*\}\s*(\w+)\s*;', text, re.S))
            for ret, name, args in re.findall(r"OVRP[L]?_PUBLIC_FUNCTION\((.*?)\)\s+(ovr_\w+)\s*\((.*?)\)\s*;", text, re.S):
                signatures[name] = (ret.strip(), args.strip())
                native.add(name)
        else:
            string_getters.update(re.findall(r'public\s+static\s+string\s+(ovr_\w+)\(', text))
            for ret, name, args in re.findall(r"(?:public|private)\s+static\s+extern\s+(\S+)\s+(ovr_\w+)\((.*?)\);", text, re.S):
                name = name.removesuffix("_Native")
                # Prefer native C signatures, which distinguish strings from
                # opaque pointers (both are IntPtr in generated C# declarations).
                signatures.setdefault(name, (ret.strip(), args.strip()))

    requests = {name: enums[name[4:]] for name, (ret, args) in signatures.items()
                if ret in ("ovrRequest", "ulong", "UInt64") and name[4:] in enums
                and not name.startswith("ovr_Platform")}
    # OVR_Functions_Networking.h explicitly associates this request with a
    # notification-named completion rather than a same-named message enum.
    requests["ovr_Net_Ping"] = enums["Notification_Networking_PingResult"]
    # Private request declarations not available in public CAPI are left
    # unresolved, even when their name looks like an asynchronous request.
    banner = "// Generated by generate.py from sdk_sources.json. Do not edit.\n"
    (HERE / "requests.inc").write_text(banner + "".join(
        f'VENTURE_REQUEST("{n}", 0x{v:08x})\n' for n, v in sorted(requests.items())))
    def arguments(args):
        return [tuple(re.match(r'(.*?)\s*\b(\w+)\s*$', a.strip()).groups())
                for a in args.split(',')] if args and args != 'void' else []

    def descriptor(name, t, arg, all_args, index):
        t = t.strip().removeprefix('const ')
        kind, tag, count = 'unsupported', '', -1
        if t in ('char *', 'string'): kind = 'string'
        elif t in ('char **', 'string[]'): kind = 'string_array'
        elif t in ('ovrID *', 'UInt64[]'): kind = 'id_array'
        elif t == 'void *': kind = 'bytes'
        elif t in ('ovrID', 'unsigned long long', 'UInt64', 'ulong'): kind = 'id'
        elif t in ('size_t', 'UIntPtr'): kind = 'size'
        elif t in ('long long', 'long', 'Int64'): kind = 'i64'
        elif t in ('unsigned int', 'uint', 'UInt32'): kind = 'u32'
        elif t == 'int': kind = 'i32'
        elif t == 'bool': kind = 'boolean'
        elif t.endswith('OptionsHandle'): kind, tag = 'options', t.removeprefix('ovr').removesuffix('Handle')
        elif t.endswith('ArrayHandle'): kind, tag = 'model', t.removeprefix('ovr').removesuffix('Handle')
        elif t in enum_types or (name not in native and t not in ('IntPtr',) and '*' not in t and '[]' not in t): kind = 'enumeration'
        elif t == 'IntPtr':
            # CAPI.cs private string wrappers use IntPtr. Options wrappers have
            # no native header in these pins, so enumerate the verified kinds.
            option_kinds = {'abuse_report_options': 'AbuseReportOptions', 'abuseReportOptions': 'AbuseReportOptions',
                'deeplink_options': 'ApplicationOptions', 'userOptions': 'UserOptions',
                'connect_options': 'NetSyncOptions'}
            if arg in option_kinds: kind, tag = 'options', option_kinds[arg]
            elif name == 'ovr_Avatar_LaunchAvatarEditor': kind, tag = 'options', 'AvatarEditorOptions'
            else: kind = 'string'
        if kind in ('string_array', 'id_array', 'bytes'):
            # All public array/blob declarations pair with a following count;
            # attenuation/struct arrays deliberately remain unsupported.
            for j in range(index + 1, len(all_args)):
                if all_args[j][0].strip() in ('int', 'unsigned int', 'size_t', 'UIntPtr'):
                    count = j; break
            if count == -1: kind = 'unsupported'
        return f'ArgDescriptor{{ArgKind::{kind}, {count}, "{tag}"}}'

    (HERE / 'request_args.inc').write_text(banner + ''.join(
        f'VENTURE_REQUEST_ARGS("{name}"' + ''.join(', ' + descriptor(name, t, a, arguments(signatures[name][1]), i)
          for i, (t, a) in enumerate(arguments(signatures[name][1]))) + ')\n'
        for name in sorted(requests)))
    options = {}
    for name, (ret, args) in signatures.items():
        match = re.fullmatch(r"ovr_(\w*Options)_(\w+)", name)
        if not match:
            continue
        kind, action = match.groups()
        types = []
        for arg in args.split(",") if args else []:
            t = arg.strip().rsplit(" ", 1)[0].strip()
            if "char" in t or (t in ("IntPtr", "string") and types): types.append("s")
            elif t == "double": types.append("d")
            elif t == "float": types.append("f")
            elif "[]" in t or "*" in t: types.append("?")
            elif t == "bool": types.append("b")
            elif t in ("ovrID", "UInt64", "ulong", "uint64_t", "long", "long long", "size_t", "UIntPtr", "IntPtr") or t.endswith("Handle"): types.append("q")
            elif t in ("unsigned int", "uint", "uint32_t"): types.append("u")
            else: types.append("i")
        if "?" in types:
            continue
        options[name] = (kind, action, "".join(types))
    (HERE / "options.inc").write_text(banner + "".join(
        f'VENTURE_OPTION("{n}", "{k}", "{a}", "{t}")\n' for n, (k, a, t) in sorted(options.items())))
    getters = sorted(n for n in signatures if n.startswith("ovr_Message_Get") or n == "ovr_Message_IsError")
    (HERE / "message_getters.inc").write_text(banner + "".join(f'VENTURE_GETTER("{n}")\n' for n in getters))
    models = {}
    for name, (ret, args) in signatures.items():
        match = re.fullmatch(r'ovr_(\w+)_(Get\w+|Is\w+|Has\w+|Contains)', name)
        if not match or name in requests or name in options: continue
        model, action = match.groups()
        aa = arguments(args)
        if not aa or 'Voip' in model or model in ('Message', 'Error', 'ApplicationLifecycle', 'Net', 'Microphone', 'NetSync'): continue
        # Only accessors of an opaque model object, not service/global calls.
        first_type, first_name = aa[0]
        if name in native and model + 'Handle' not in first_type: continue
        if name not in native and first_name not in ('obj', 'handle'): continue
        field = action[3:] if action.startswith('Get') else action
        rt = ret.removeprefix('const ').strip()
        kind, nested, op = 'scalar', '', 'field'
        if rt in ('char *', 'char*', 'string') or name in string_getters: kind = 'string'
        elif rt == 'float': kind = 'f32'
        elif rt == 'double': kind = 'f64'
        elif rt.endswith('Handle'): kind, nested = 'model', rt.removeprefix('ovr').removesuffix('Handle')
        elif rt == 'IntPtr': kind, nested = 'model', field
        if field in ('Data', 'ExtraData') and kind in ('string', 'model'): kind, nested = 'blob', ''
        if model.endswith('Array'):
            if field == 'Element': op, kind, nested = 'element', 'model', model.removesuffix('Array')
            elif field == 'Size': op = 'size'
            elif action == 'HasNextPage': op = 'has_next'
            elif action == 'HasPreviousPage': op = 'has_previous'
        if model == 'DataStore':
            op = {'Key': 'dict_key', 'Value': 'dict_value', 'NumKeys': 'dict_size', 'Contains': 'dict_contains'}[field]
        elif len(aa) == 2 and op == 'field' and kind == 'scalar':
            # OVR_MatchmakingEnqueuedUser / CAPI LeaderboardUpdateStatus expose
            # indexed ovrID fields paired with a Get...sSize accessor.
            assert aa[1][1] == 'index', (name, aa)
            op = 'indexed'
        models[name] = (model, field, kind, op, nested)
    for model, field, kind, op, nested in list(models.values()):
        if op == 'indexed':
            size_name = f'ovr_{model}_Get{field}sSize'
            assert size_name in models, size_name
            models[size_name] = (model, field, 'scalar', 'indexed_size', '')
    # Meta's signed 1.205 DLL exports these newer IAP accessors (RVA
    # 0x7aa10..0x7ab60, 0x7c470..0x7c6d0, 0x83180..0x831c0,
    # 0x839f0..0x83da0, 0x84230, 0x859d0..0x85bb0). The pinned 207
    # SDK iap/Models and Enums confirm their fields/types; its new managed
    # bridge no longer publishes the corresponding CAPI declarations.
    for model, fields in {
        'Product': {'BillingPlans': 'BillingPlanArray', 'ContentRating': 'ContentRating',
                    'CoverUrl': 'string', 'IconUrl': 'string', 'ShortDescription': 'string', 'Type': 'scalar'},
        'Purchase': {'Type': 'scalar'},
        'BillingPlan': {'PaidOffer': 'PaidOffer', 'TrialOffers': 'TrialOfferArray'},
        'PaidOffer': {'Price': 'Price', 'SubscriptionTerm': 'scalar'},
        'TrialOffer': {'Price': 'Price', 'MaxTermCount': 'scalar', 'TrialTerm': 'scalar', 'TrialType': 'scalar'},
        'ContentRating': {'AgeRatingImageUri': 'string', 'AgeRatingText': 'string', 'RatingDefinitionUri': 'string'},
    }.items():
        for field, typ in fields.items():
            kind = typ if typ in ('string', 'scalar') else 'model'
            models[f'ovr_{model}_Get{field}'] = (model, field, kind, 'field', typ if kind == 'model' else '')
    for model in ('BillingPlanArray', 'TrialOfferArray'):
        models[f'ovr_{model}_GetElement'] = (model, 'Element', 'model', 'element', model.removesuffix('Array'))
        models[f'ovr_{model}_GetSize'] = (model, 'Size', 'scalar', 'size', '')
    for field in ('Descriptor', 'InteractiveElement'):
        models[f'ovr_ContentRating_Get{field}'] = ('ContentRating', field + 's', 'string', 'indexed', '')
        models[f'ovr_ContentRating_Get{field}sSize'] = ('ContentRating', field + 's', 'scalar', 'indexed_size', '')
    (HERE / 'model_getters.inc').write_text(banner + ''.join(
        f'VENTURE_MODEL_GETTER("{n}", "{m}", "{f}", {k}, {o}, "{nested}")\n'
        for n, (m, f, k, o, nested) in sorted(models.items())))
    print(f"Generated {len(requests)} requests, {len(options)} option operations, {len(getters)} message getters")
    if not evidence:
        # Preserve the measured corpus's source columns while refreshing which
        # helpers/tables are actually registered, without requiring APKs.
        coverage = ROOT / 'tests/runtime/ovrplatform_coverage.txt'
        manual = set(re.findall(r'VENTURE_EXPORT\(\s*"([^\"]+)"', (HERE / 'hle.cpp').read_text()))
        implemented = set(requests) | set(options) | set(getters) | set(models) | manual
        lines = coverage.read_text().splitlines()
        for i, line in enumerate(lines):
            columns = line.split('\t')
            if len(columns) == 4 and columns[0] != 'name':
                if columns[0] not in implemented: columns[1] = 'MISSING'
                elif columns[1] == 'MISSING': columns[1] = 'COMPLETE' if columns[0] in requests else 'LOCAL'
                lines[i] = '\t'.join(columns)
        coverage.write_text('\n'.join(lines) + '\n')
        return
    evidence = Path(evidence)
    union = list(csv.DictReader((evidence / "export-union.tsv").open(), delimiter="\t"))
    assert len(union) == 1136
    summary = json.loads((evidence / "summary.json").read_text())
    refs = {}
    for game in summary:
        for path, info in game["files"].items():
            if "ovrplatformloader" in path:
                continue
            for key, tag in [("imports", "I"), ("string_names", "R")]:
                for name in info.get(key, []):
                    if isinstance(name, dict): name = name["name"]
                    refs.setdefault(name, set()).add(game["package"] + ":" + tag)
    manual = set(re.findall(r'VENTURE_EXPORT\(\s*"([^\"]+)"', (HERE / "hle.cpp").read_text()))
    implemented = set(requests) | set(options) | set(getters) | set(models) | manual
    lines = ["# r5 export union: I=undefined import, R=retained name (neither proves runtime use).",
             "# COMPLETE=request always completes, often with a truthful unsupported error.",
             "# LOCAL=queue/accessors/options/lifecycle; MISSING=unregistered, normal missing-symbol diagnostic.",
             "name\tstatus\texported_by\treferenced_by"]
    for item in union:
        name = item["name"]
        status = "COMPLETE" if name in requests or name == "ovr_HTTP_GetWithMessageType" else "LOCAL" if name in implemented else "MISSING"
        lines.append("\t".join([name, status, item["packages"], ",".join(sorted(refs.get(name, []))) or "-"]))
    (ROOT / "tests/runtime/ovrplatform_coverage.txt").write_text("\n".join(lines) + "\n")
    print(f"Corpus coverage: {len(set(x['name'] for x in union) & implemented)}/1136 registered")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence")
    generate(parser.parse_args().evidence)
