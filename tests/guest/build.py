#!/usr/bin/env python3
"""Build Android guest fixtures, manifests and undefined-symbol reports. Never run them."""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

EXE = ".exe" if os.name == "nt" else ""
NDK_HOST = "windows-x86_64" if os.name == "nt" else "linux-x86_64"

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tests/guest"
VARIANTS = {
    "arm64-v8a-android32": ("arm64-v8a", 32, "c++_static"),
    "arm64-v8a-android23": ("arm64-v8a", 23, "c++_static"),
    "armeabi-v7a-android23": ("armeabi-v7a", 23, "c++_static"),
    "arm64-v8a-android32-shared": ("arm64-v8a", 32, "c++_shared"),
}
TESTS = ["strings", "printf", "parse", "malloc", "libm", "cpp", "lifecycle",
         "pthreads", "tls", "atomics", "jumps", "signals", "time", "files",
         "dl", "misc", "log", "neon", "jni", "ndk_api"]
PEERS = {"cpp": ["libvtest_cpp_peer.so"], "cpp_shared": ["libvtest_cpp_peer.so", "libc++_shared.so"],
         "lifecycle": ["libvtest_lifecycle_peer.so"], "tls": ["libvtest_tls_peer.so"],
         "dl": ["libvtest_dl_peer.so"]}
API_GUARDS = {"malloc": ["aligned_alloc (API >= 28)"],
              "pthreads": ["pthread_barrier_* (API >= 24)", "pthread_getname_np (API >= 26; prctl on older APIs)"],
              "neon": ["dot product requires AArch64 HWCAP_ASIMDDP"],
              "atomics": ["128-bit atomics require AArch64"],
              "ndk_api": ["AChoreographer_* (API >= 24)"]}


def run(args: list[str]) -> None:
    subprocess.run(args, cwd=ROOT, check=True)


def report(out: Path, ndk: Path, variant: str, abi: str, api: int, stl: str) -> None:
    readelf = ndk / f"toolchains/llvm/prebuilt/{NDK_HOST}/bin/llvm-readelf{EXE}"
    libraries = sorted(out.glob("*.so"))
    imports = ["# Undefined dynamic symbols (including weak imports), generated by llvm-readelf\n"]
    artifacts = {}
    for library in libraries:
        symbols = subprocess.check_output([str(readelf), "--dyn-syms", "--wide", str(library)], text=True)
        undefined = sorted({line.split()[-1] for line in symbols.splitlines()
                            if re.search(r"\bUND\b", line) and line.split()[-1] != "UND"})
        dynamic = subprocess.check_output([str(readelf), "--dynamic", "--wide", str(library)], text=True)
        needed = re.findall(r"\(NEEDED\).*?\[(.*?)\]", dynamic)
        headers = subprocess.check_output([str(readelf), "--program-headers", "--wide", str(library)], text=True)
        elf = subprocess.check_output([str(readelf), "--file-header", "--wide", str(library)], text=True)
        expected_machine = "AArch64" if abi == "arm64-v8a" else "ARM"
        if not re.search(rf"Machine:\s+{expected_machine}\s*$", elf, re.M) or "DYN (Shared object file)" not in elf:
            raise RuntimeError(f"unexpected ELF ABI/type: {library}")
        artifacts[library.name] = {"undefined_symbols": undefined, "needed": needed,
                                   "elf_tls": bool(re.search(r"^\s+TLS\s", headers, re.M)),
                                   "relr": "(RELR)" in dynamic or "(ANDROID_RELR)" in dynamic,
                                   "android_packed_relocations": "(ANDROID_REL" in dynamic}
        artifacts[library.name]["defined_symbols"] = sorted({line.split()[-1] for line in symbols.splitlines()
                                                             if re.search(r"^\s*\d+:", line) and " UND " not in line})
        imports.extend([f"\n[{library.name}]\n", *(f"{symbol}\n" for symbol in undefined)])
    (out / "imports.txt").write_text("".join(imports), encoding="utf-8", newline="\n")
    tests = ["cpp_shared"] if stl == "c++_shared" else TESTS
    entries = []
    for name in tests:
        expected = SOURCE / "expected" / f"{name}.txt"
        if not expected.is_file():
            raise RuntimeError(f"missing expected output: {expected}")
        if "vtest_main" not in artifacts[f"libvtest_{name}.so"]["defined_symbols"]:
            raise RuntimeError(f"missing vtest_main: {name}")
        if not expected.read_bytes().endswith(f"VTEST RESULT {name} PASS\n".encode()):
            raise RuntimeError(f"invalid final expected-output line: {expected}")
        for peer in PEERS.get(name, []):
            if peer not in artifacts:
                raise RuntimeError(f"missing support library: {peer}")
        entries.append({"name": name, "library": f"libvtest_{name}.so", "entry": "vtest_main",
                        "expected_stdout": expected.relative_to(ROOT).as_posix(),
                        "support_libraries": PEERS.get(name, []),
                        "argv": [f"libvtest_{name}.so", "${TEST_DIR}"] if name == "files" else [f"libvtest_{name}.so"],
                        "timeout_seconds": 60 if name in ("malloc", "pthreads", "misc") else 30,
                        "requires_java_bridge": name == "jni", "api_guards": API_GUARDS.get(name, [])})
    manifest = {"schema_version": 1, "variant": variant, "abi": abi, "android_platform": api,
                "stl": stl, "tls_model": "elf" if api >= 29 else "emutls",
                "ndk_revision": (ndk / "source.properties").read_text().split("Pkg.Revision = ")[1].splitlines()[0],
                "runner": None if stl == "c++_shared" else "vtest_runner", "fresh_process_per_test": True,
                "drain_guest_threads_before_unload": True, "tests": entries,
                "artifacts": artifacts}
    # Audit actual linked artifacts, not just compiler settings.
    if stl != "c++_shared":
        for module in ("libvtest_tls.so", "libvtest_tls_peer.so"):
            tls = artifacts[module]
            if tls["elf_tls"] != (api >= 29):
                raise RuntimeError(f"wrong TLS model in {variant}: {module}")
            if api >= 29 and not tls["relr"]:
                raise RuntimeError(f"missing RELR in {variant}: {module}")
            if api < 29 and not tls["android_packed_relocations"]:
                raise RuntimeError(f"missing Android packed relocations in {variant}: {module}")
        runner_header = subprocess.check_output([str(readelf), "--file-header", str(out / "vtest_runner")], text=True)
        if not re.search(r"Type:\s+DYN", runner_header):
            raise RuntimeError(f"runner is not PIE: {variant}")
        for export in ("JNI_OnLoad", "Java_org_venture_tests_VtestJni_nativeMultiply",
                       "Java_org_venture_tests_VtestJni_nativeGreeting", "Java_org_venture_tests_VtestJni_runGuest"):
            if export not in artifacts["libvtest_jni.so"]["defined_symbols"]:
                raise RuntimeError(f"missing JNI export: {export}")
    elif "libc++_shared.so" not in artifacts["libvtest_cpp_shared.so"]["needed"]:
        raise RuntimeError("shared C++ test did not link libc++_shared")
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--variant", choices=VARIANTS, action="append", help="only build these variants (default: all)")
    parser.add_argument("--jobs", type=int, default=min(os.cpu_count() or 2, 8))
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    ndk = ROOT / ".deps/android-ndk"
    cmake = ROOT / f".deps/cmake/bin/cmake{EXE}"
    ninja = ROOT / f".deps/ninja/ninja{EXE}"
    for path in (ndk / "build/cmake/android.toolchain.cmake", cmake, ninja):
        if not path.exists():
            parser.error("missing toolchain; run python tools/bootstrap.py --ndk first")
    for variant in args.variant or VARIANTS:
        abi, api, stl = VARIANTS[variant]
        out = ROOT / "build/guest" / variant
        out.mkdir(parents=True, exist_ok=True)
        # A failed rebuild must not leave a manifest advertising stale binaries.
        (out / "manifest.json").unlink(missing_ok=True)
        run([str(cmake), "-S", str(SOURCE), "-B", str(out), "-G", "Ninja",
             f"-DCMAKE_MAKE_PROGRAM={ninja.as_posix()}",
             f"-DCMAKE_TOOLCHAIN_FILE={(ndk / 'build/cmake/android.toolchain.cmake').as_posix()}",
             f"-DANDROID_ABI={abi}", f"-DANDROID_PLATFORM=android-{api}", f"-DANDROID_STL={stl}",
             "-DCMAKE_BUILD_TYPE=Release", f"-DVTEST_SHARED_ONLY={'ON' if stl == 'c++_shared' else 'OFF'}"])
        run([str(cmake), "--build", str(out), "--parallel", str(args.jobs)])
        if stl == "c++_shared":
            triple = "aarch64-linux-android"
            shutil.copy2(ndk / f"toolchains/llvm/prebuilt/{NDK_HOST}/sysroot/usr/lib/{triple}/libc++_shared.so", out)
        report(out, ndk, variant, abi, api, stl)
        print(f"{variant}: built; manifest.json and imports.txt written", flush=True)


if __name__ == "__main__":
    main()
